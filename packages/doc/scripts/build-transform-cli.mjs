// Builds dist/transform-cli.js (docs/contracts/ms4-jobs.md §2.2): a launcher that lets plain Node run the engine's
// TypeScript sources (type stripping, Node ≥ 22.18) with the `.js` → `.ts` resolver, so the Rust tests' transformer
// runs exactly the sources under test. Usage: npm run build (in packages/doc).
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
mkdirSync(join(root, 'dist'), { recursive: true })
writeFileSync(
  join(root, 'dist/transform-cli.js'),
  "// Generated by scripts/build-transform-cli.mjs. Do not edit.\n" +
    "import '../scripts/ts-resolve.mjs'\n" +
    "await import('../src/transform-cli.ts')\n",
)
